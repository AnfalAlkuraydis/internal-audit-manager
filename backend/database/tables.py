"""Define stored records and database-level relationship/date constraints.

schemas.py validates incoming Python/JSON data; these SQLAlchemy definitions
describe its storage. Importing this file creates no database tables. Alembic
owns schema changes. Phase 3 adds frozen execution and human-review history.
"""
import sqlalchemy as sa

metadata = sa.MetaData()
# Source authority and allowed evidence kinds describe the fictional source systems.
sources = sa.Table("sources", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("system", sa.String, nullable=False),
    sa.Column("authority", sa.String, nullable=False),
    sa.Column("allowed_kinds", sa.JSON, nullable=False),
    sa.CheckConstraint("authority IN ('original', 'secondary')", name="source_authority"))
# Versioned policy requirements apply only during their effective date interval.
policies = sa.Table("policies", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("title", sa.String, nullable=False),
    sa.Column("version", sa.Integer, nullable=False),
    sa.Column("department", sa.String, nullable=False),
    sa.Column("effective_from", sa.Date, nullable=False),
    sa.Column("effective_to", sa.Date),
    sa.Column("text", sa.String, nullable=False),
    sa.CheckConstraint("version > 0", name="policy_version"),
    sa.CheckConstraint("effective_to IS NULL OR effective_to >= effective_from", name="policy_dates"))
# Each control belongs to a policy and names the population it checks.
controls = sa.Table("controls", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("policy_id", sa.String, sa.ForeignKey("policies.id"), nullable=False),
    sa.Column("title", sa.String, nullable=False),
    sa.Column("entity_kind", sa.String, nullable=False),
    sa.Column("requirement", sa.String, nullable=False),
    sa.CheckConstraint("entity_kind IN ('project', 'privileged_account', 'device')", name="control_kind"))
# Rules are structured JSON instructions, never Python code to execute.
procedures = sa.Table("procedures", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("control_id", sa.String, sa.ForeignKey("controls.id"), nullable=False, unique=True),
    sa.Column("version", sa.Integer, nullable=False),
    sa.Column("instructions", sa.String, nullable=False),
    sa.Column("rule", sa.JSON, nullable=False),
    sa.CheckConstraint("version > 0", name="procedure_version"))
# Keep development and held-out evidence in identifiable, separate partitions.
datasets = sa.Table("datasets", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("version", sa.Integer, nullable=False),
    sa.Column("split", sa.String, nullable=False),
    sa.Column("department", sa.String, nullable=False),
    sa.Column("description", sa.String, nullable=False),
    sa.Column("fingerprint", sa.String(64), nullable=False),
    sa.CheckConstraint("split IN ('development', 'held_out')", name="dataset_split"),
    sa.CheckConstraint("version > 0", name="dataset_version"))
# A population member is a project, privileged account, or managed device.
entities = sa.Table("entities", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("dataset_id", sa.String, sa.ForeignKey("datasets.id"), nullable=False, index=True),
    sa.Column("source_id", sa.String, sa.ForeignKey("sources.id"), nullable=False),
    sa.Column("kind", sa.String, nullable=False),
    sa.Column("name", sa.String, nullable=False),
    sa.Column("active_from", sa.Date, nullable=False),
    sa.Column("active_to", sa.Date),
    sa.Column("facts", sa.JSON, nullable=False),
    sa.UniqueConstraint("id", "dataset_id", name="entity_dataset"),
    sa.CheckConstraint("active_to IS NULL OR active_to >= active_from", name="entity_dates"),
    sa.CheckConstraint("kind IN ('project', 'privileged_account', 'device')", name="entity_kind"))
# Retain original source IDs, dates and versions so audit claims can be traced.
evidence = sa.Table("evidence", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("dataset_id", sa.String, sa.ForeignKey("datasets.id"), nullable=False, index=True),
    sa.Column("entity_id", sa.String, nullable=False),
    sa.Column("source_id", sa.String, sa.ForeignKey("sources.id"), nullable=False),
    sa.Column("source_record_id", sa.String, nullable=False),
    sa.Column("kind", sa.String, nullable=False),
    sa.Column("version", sa.Integer, nullable=False),
    sa.Column("observed_on", sa.Date, nullable=False),
    sa.Column("captured_on", sa.Date, nullable=False),
    sa.Column("supersedes_id", sa.String),
    sa.Column("facts", sa.JSON, nullable=False),
    sa.Column("fingerprint", sa.String(64), nullable=False),
    sa.UniqueConstraint("id", "dataset_id", name="evidence_dataset"),
    sa.UniqueConstraint("dataset_id", "source_id", "source_record_id", "version", name="source_version"),
    # Including dataset_id prevents links into a different evaluation partition.
    sa.ForeignKeyConstraint(["entity_id", "dataset_id"], ["entities.id", "entities.dataset_id"]),
    sa.ForeignKeyConstraint(["supersedes_id", "dataset_id"], ["evidence.id", "evidence.dataset_id"]),
    sa.CheckConstraint("version > 0", name="evidence_version"),
    sa.CheckConstraint("captured_on >= observed_on", name="evidence_dates"))
# An engagement selects a department, dataset and inclusive audit period.
engagements = sa.Table("engagements", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("dataset_id", sa.String, sa.ForeignKey("datasets.id"), nullable=False),
    sa.Column("department", sa.String, nullable=False),
    sa.Column("period_start", sa.Date, nullable=False),
    sa.Column("period_end", sa.Date, nullable=False),
    sa.CheckConstraint("period_end >= period_start", name="engagement_dates"))

# Phase 3 proposals and calculated artifacts have separate, append-only histories.
proposals = sa.Table("proposals", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id"), nullable=False, index=True),
    sa.Column("kind", sa.String, nullable=False),
    sa.Column("business_key", sa.String, nullable=False),
    sa.UniqueConstraint("engagement_id", "kind", "business_key", name="proposal_business_key"),
    sa.CheckConstraint("kind IN ('plan','finding','escalation','closure')", name="proposal_kind"))
proposal_versions = sa.Table("proposal_versions", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("proposal_id", sa.String, sa.ForeignKey("proposals.id"), nullable=False),
    sa.Column("version", sa.Integer, nullable=False),
    sa.Column("document", sa.JSON, nullable=False),
    sa.Column("created_by", sa.String, nullable=False),
    sa.Column("created_at", sa.String, nullable=False),
    sa.UniqueConstraint("proposal_id", "version", name="proposal_version"))
review_decisions = sa.Table("review_decisions", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("version_id", sa.String, sa.ForeignKey("proposal_versions.id"), nullable=False, unique=True),
    sa.Column("decision", sa.String, nullable=False),
    sa.Column("reviewer_id", sa.String, nullable=False),
    sa.Column("reviewer_role", sa.String, nullable=False),
    sa.Column("reason", sa.String, nullable=False),
    sa.Column("created_at", sa.String, nullable=False),
    sa.CheckConstraint("decision IN ('approved','rejected','changes_requested')", name="review_decision"),
    sa.CheckConstraint("reviewer_role IN ('auditor','reviewer')", name="human_reviewer"))
# Each artifact contains a frozen population, evidence selection or calculated run.
artifacts = sa.Table("artifacts", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id"), nullable=False, index=True),
    sa.Column("kind", sa.String, nullable=False),
    sa.Column("digest", sa.String(64), nullable=False, unique=True),
    sa.Column("payload", sa.JSON, nullable=False),
    sa.Column("created_at", sa.String, nullable=False),
    sa.CheckConstraint("kind IN ('population','evidence','run')", name="artifact_kind"))
test_results = sa.Table("test_results", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("run_id", sa.String, sa.ForeignKey("artifacts.id"), nullable=False, index=True),
    sa.Column("entity_id", sa.String, sa.ForeignKey("entities.id"), nullable=False),
    sa.Column("control_id", sa.String, sa.ForeignKey("controls.id"), nullable=False),
    sa.Column("outcome", sa.String, nullable=False),
    sa.Column("reason", sa.String, nullable=False),
    sa.Column("evidence_ids", sa.JSON, nullable=False),
    sa.UniqueConstraint("run_id", "entity_id", name="run_member"),
    sa.CheckConstraint("outcome IN ('PASS','FAIL','MISSING_EVIDENCE','CONTRADICTORY_EVIDENCE','ERROR','NOT_APPLICABLE')", name="test_outcome"))
evidence_requests = sa.Table("evidence_requests", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id"), nullable=False),
    sa.Column("business_key", sa.String, nullable=False, unique=True),
    sa.Column("document", sa.JSON, nullable=False),
    sa.Column("status", sa.String, nullable=False),
    sa.Column("proposal_id", sa.String, sa.ForeignKey("proposals.id")),
    sa.Column("created_at", sa.String, nullable=False),
    sa.CheckConstraint("status IN ('queued','waiting_for_approval','sent','received','resolved','cancelled')", name="request_status"))
action_plans = sa.Table("action_plans", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("finding_id", sa.String, sa.ForeignKey("proposals.id"), nullable=False),
    sa.Column("document", sa.JSON, nullable=False),
    sa.Column("recorded_by", sa.String, nullable=False),
    sa.Column("created_at", sa.String, nullable=False))
# A caller key cannot be reused with different arguments or a different tool.
action_receipts = sa.Table("action_receipts", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("actor_id", sa.String, nullable=False),
    sa.Column("operation_id", sa.String, nullable=False),
    sa.Column("input_digest", sa.String, nullable=False),
    sa.Column("result", sa.JSON, nullable=False),
    sa.UniqueConstraint("actor_id", "operation_id", name="actor_operation"))
audit_events = sa.Table("audit_events", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id"), nullable=False),
    sa.Column("actor_id", sa.String, nullable=False),
    sa.Column("actor_role", sa.String, nullable=False),
    sa.Column("event", sa.String, nullable=False),
    sa.Column("record_id", sa.String, nullable=False),
    sa.Column("created_at", sa.String, nullable=False))


# Phase 4: durable single-agent sessions and event-driven simulated communication.
agent_sessions = sa.Table("agent_sessions", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id"), unique=True),
    sa.Column("dataset_id", sa.String, sa.ForeignKey("datasets.id"), nullable=False),
    sa.Column("assignment", sa.String, nullable=False),
    sa.Column("status", sa.String, nullable=False),
    sa.Column("wake_version", sa.Integer, nullable=False),
    sa.Column("handled_version", sa.Integer, nullable=False),
    sa.Column("last_business_event", sa.String, nullable=False),
    sa.Column("lease_owner", sa.String),
    sa.Column("lease_until", sa.String),
    sa.Column("error_code", sa.String),
    sa.Column("updated_at", sa.String, nullable=False))
agent_inferences = sa.Table("agent_inferences", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("session_id", sa.String, sa.ForeignKey("agent_sessions.id"), nullable=False),
    sa.Column("turn_key", sa.String, nullable=False),
    sa.Column("request_digest", sa.String, nullable=False),
    sa.Column("response", sa.JSON, nullable=False),
    sa.Column("offered_tools", sa.JSON, nullable=False),
    sa.Column("created_at", sa.String, nullable=False),
    sa.UniqueConstraint("session_id", "turn_key", name="session_inference_turn"))
agent_calls = sa.Table("agent_calls", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("session_id", sa.String, sa.ForeignKey("agent_sessions.id"), nullable=False),
    sa.Column("call_id", sa.String, nullable=False),
    sa.Column("tool", sa.String, nullable=False),
    sa.Column("arguments", sa.JSON, nullable=False),
    sa.Column("result", sa.JSON, nullable=False),
    sa.Column("success", sa.Boolean, nullable=False),
    sa.Column("schema_valid", sa.Boolean, nullable=False),
    sa.Column("duration_ms", sa.Float, nullable=False),
    sa.Column("created_at", sa.String, nullable=False),
    sa.UniqueConstraint("session_id", "call_id", name="session_tool_call"))
work_items = sa.Table("work_items", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id"), nullable=False),
    sa.Column("control_id", sa.String, sa.ForeignKey("controls.id"), nullable=False),
    sa.Column("purpose", sa.String, nullable=False),
    sa.Column("plan_version_id", sa.String, sa.ForeignKey("proposal_versions.id"), nullable=False),
    sa.Column("finding_id", sa.String),
    sa.Column("state", sa.String, nullable=False),
    sa.Column("latest_run_id", sa.String, sa.ForeignKey("artifacts.id")),
    sa.Column("updated_at", sa.String, nullable=False))
activity = sa.Table("activity", metadata,
    sa.Column("id", sa.Integer, primary_key=True, autoincrement=True),
    sa.Column("event_key", sa.String, nullable=False, unique=True),
    sa.Column("session_id", sa.String, sa.ForeignKey("agent_sessions.id")),
    sa.Column("engagement_id", sa.String, sa.ForeignKey("engagements.id")),
    sa.Column("status", sa.String, nullable=False),
    sa.Column("label", sa.String, nullable=False),
    sa.Column("record_type", sa.String),
    sa.Column("record_id", sa.String),
    sa.Column("details", sa.JSON, nullable=False),
    sa.Column("created_at", sa.String, nullable=False))
mail_followups = sa.Table("mail_followups", metadata,
    sa.Column("request_id", sa.String, sa.ForeignKey("evidence_requests.id"), primary_key=True),
    sa.Column("due_at", sa.String, nullable=False),
    sa.Column("interval_days", sa.Integer, nullable=False),
    sa.Column("next_reminder_at", sa.String, nullable=False),
    sa.Column("reminder_count", sa.Integer, nullable=False),
    sa.Column("state", sa.String, nullable=False),
    sa.Column("escalation_proposal_id", sa.String, sa.ForeignKey("proposals.id")),
    sa.Column("updated_at", sa.String, nullable=False))
mail_outbox = sa.Table("mail_outbox", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("request_id", sa.String, sa.ForeignKey("evidence_requests.id"), nullable=False),
    sa.Column("kind", sa.String, nullable=False),
    sa.Column("ordinal", sa.Integer, nullable=False),
    sa.Column("message_id", sa.String, nullable=False, unique=True),
    sa.Column("review_version_id", sa.String, sa.ForeignKey("proposal_versions.id")),
    sa.Column("envelope", sa.JSON, nullable=False),
    sa.Column("status", sa.String, nullable=False),
    sa.Column("attempts", sa.Integer, nullable=False),
    sa.Column("error_code", sa.String),
    sa.Column("created_at", sa.String, nullable=False),
    sa.UniqueConstraint("request_id", "kind", "ordinal", name="request_mail_action"))
simulated_deliveries = sa.Table("simulated_deliveries", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("outbox_id", sa.String, sa.ForeignKey("mail_outbox.id"), nullable=False, unique=True),
    sa.Column("message_id", sa.String, nullable=False, unique=True),
    sa.Column("envelope", sa.JSON, nullable=False),
    sa.Column("delivered_at", sa.String, nullable=False))
mail_inbox = sa.Table("mail_inbox", metadata,
    sa.Column("id", sa.String, primary_key=True),
    sa.Column("request_id", sa.String, sa.ForeignKey("evidence_requests.id")),
    sa.Column("digest", sa.String, nullable=False),
    sa.Column("sender", sa.String, nullable=False),
    sa.Column("in_reply_to", sa.String, nullable=False),
    sa.Column("payload", sa.JSON, nullable=False),
    sa.Column("status", sa.String, nullable=False),
    sa.Column("validation_code", sa.String, nullable=False),
    sa.Column("received_at", sa.String, nullable=False))
